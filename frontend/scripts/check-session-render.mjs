import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';
const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom' });
try {
  const { default: StudentEventCard } = await server.ssrLoadModule('/src/components/student/StudentEventCard.jsx');
  const { default: SessionSetupEditor } = await server.ssrLoadModule('/src/components/shared/SessionSetupEditor.jsx');
  const { default: ManagedEventCard } = await server.ssrLoadModule('/src/components/shared/ManagedEventCard.jsx');
  const session = { _id: 'morning', name: 'Morning session', timeInOpen: '2026-11-08T00:00:00Z', onTimeDeadline: '2026-11-08T00:30:00Z', timeInCutoff: '2026-11-08T01:00:00Z', timeOutOpen: '2026-11-08T03:00:00Z', timeOutClose: '2026-11-08T04:00:00Z' };
  const event = { _id: 'event', title: 'CCIT assembly', status: 'live', date: '2026-11-08', time: '08:00', endTime: '12:00', attendanceStartTime: '08:00', attendanceEndTime: '08:30', attendanceSessions: [session, { ...session, _id: 'afternoon', name: 'Afternoon session' }] };
  const records = [{ session: 'morning', sessionName: session.name, timeInAt: session.timeInOpen, timeOutAt: session.timeOutOpen, arrivalStatus: 'on_time', completionStatus: 'completed', status: 'present' }, { session: 'afternoon', sessionName: 'Afternoon session', timeInAt: session.timeInOpen, arrivalStatus: 'late', completionStatus: 'incomplete', status: 'late' }];
  const render = (Component, props) => renderToStaticMarkup(React.createElement(Component, props));
  const student = render(StudentEventCard, { event, records });
  assert.match(student, /Completed/); assert.match(student, /Incomplete/);
  assert.match(student, /Late \(4h\) \+ missing Time Out \(2h\): 6h/);
  assert.match(student, /Afternoon session/);
  assert.equal((student.match(/>Time In<\/p>/g) || []).length, 2, 'each session prints a Time In heading once');
  const legacy = render(StudentEventCard, { event: { ...event, attendanceSessions: [] }, attendance: { status: 'present' } });
  assert.doesNotMatch(legacy, /Time Out|Incomplete/);
  const editor = render(SessionSetupEditor, { value: { ...event, attendanceSessions: [session] }, onChange() {} });
  assert.equal((editor.match(/type="date"/g) || []).length, 2);
  assert.equal((editor.match(/aria-haspopup="dialog"/g) || []).length, 5);
  assert.doesNotMatch(editor, /type="datetime-local"/);
  const blank = render(SessionSetupEditor, { value: { attendanceSessions: [] }, onChange() {} });
  assert.match(blank, /Time In/); assert.match(blank, /Time Out/);
  assert.match(blank, /Add another day \/ activity/);
  assert.doesNotMatch(blank, /Session 1|Session name|Attendance sessions/);
  assert.equal((blank.match(/type="date"/g) || []).length, 2);
  assert.match(editor, /value="2026-11-08"/);
  assert.match(editor, /value="08:00"/);
  const { default: EventAttendanceSchedule } = await server.ssrLoadModule('/src/components/shared/EventAttendanceSchedule.jsx');
  const { attendanceWindowLabel } = await server.ssrLoadModule('/src/utils/attendanceWindowLabel.js');
  const schedule = render(EventAttendanceSchedule, { event: { ...event, attendanceSessions: [session] } });
  assert.match(schedule, /Time In/); assert.match(schedule, /Time Out/);
  assert.match(schedule, /8:00 AM – 9:00 AM/);
  assert.match(schedule, /11:00 AM – 12:00 PM/);
  assert.match(schedule, /Late after 8:30 AM/);
  assert.doesNotMatch(schedule, /<details/);
  assert.match(attendanceWindowLabel('2026-11-08T15:00:00Z', '2026-11-08T16:30:00Z'), /Nov 8.*Nov 9/);
  assert.match(render(EventAttendanceSchedule, { event: { ...event, attendanceSessions: [] } }), /Time In only · no Time Out required/);
  const { default: EventCreateForm } = await server.ssrLoadModule('/src/components/shared/EventCreateForm.jsx');
  const draftEvent = { title: '', description: '', location: '', date: '2026-11-08', time: '', endDate: '', endTime: '', attendanceSessions: [], academicYearStart: null, semester: null };
  const initialForm = render(EventCreateForm, { value: draftEvent, onChange() {}, onSubmit() {} });
  assert.doesNotMatch(initialForm, /aria-label="Time In attendance times"|aria-label="Time Out attendance times"/);
  const startForm = render(EventCreateForm, { value: { ...draftEvent, time: '08:00' }, onChange() {}, onSubmit() {} });
  assert.match(startForm, /aria-label="Time In attendance times"/);
  assert.doesNotMatch(startForm, /aria-label="Time Out attendance times"/);
  const completeForm = render(EventCreateForm, { value: { ...draftEvent, time: '08:00', endTime: '17:00' }, onChange() {}, onSubmit() {} });
  assert.match(completeForm, /aria-label="Time Out attendance times"/);
  assert.equal((completeForm.match(/type="date"/g) || []).length, 2, 'primary attendance uses the event dates without duplicate date pickers');
  const { attendanceSetupIssue, rebaseEventAttendanceDates } = await server.ssrLoadModule('/src/utils/attendanceSessions.js');
  const valid = { ...event, endTime: '12:00', attendanceSessions: [{ ...session, name: 'Event attendance', onTimeDeadline: session.timeInOpen }] };
  assert.equal(attendanceSetupIssue(valid), '', 'zero-minute late grace is valid');
  assert.match(attendanceSetupIssue({ ...valid, attendanceSessions: [{ ...valid.attendanceSessions[0], onTimeDeadline: '2026-11-07T23:59:00Z' }] }), /Late after cannot/);
  const moved = rebaseEventAttendanceDates(valid, { ...valid, date: '2026-11-09' });
  assert.equal(moved.attendanceSessions[0].timeInOpen, '2026-11-09T00:00:00.000Z');
  assert.equal(moved.attendanceSessions[0].timeOutOpen, '2026-11-09T03:00:00.000Z');
  const { splitEventsByLifecycle } = await server.ssrLoadModule('/src/utils/helpers.js');
  const departureEvent = { ...event, status: 'finished', attendanceSessions: [{ ...session, timeOutOpen: '2026-11-08T09:01:00Z', timeOutClose: '2026-11-08T10:00:00Z' }] };
  assert.equal(splitEventsByLifecycle([departureEvent], new Date('2026-11-08T09:30:00Z')).active.length, 1);
  assert.equal(splitEventsByLifecycle([departureEvent], new Date('2026-11-08T10:01:00Z')).past.length, 1);
  assert.equal(splitEventsByLifecycle([{ ...departureEvent, status: 'closed' }], new Date('2026-11-08T09:30:00Z')).active.length, 0);
  const { updateAttendanceGroup, attendanceGroupDate, attendanceClock } = await server.ssrLoadModule('/src/utils/attendanceSessions.js');
  const arrival = { id: 'timeIn', fields: [['timeInOpen'], ['onTimeDeadline'], ['timeInCutoff']] };
  let draft = updateAttendanceGroup({}, arrival, '2026-11-08', 'timeInOpen', '23:00');
  draft = updateAttendanceGroup(draft, arrival, '2026-11-08', 'onTimeDeadline', '23:30');
  draft = updateAttendanceGroup(draft, arrival, '2026-11-08', 'timeInCutoff', '00:30');
  assert.equal(draft.timeInCutoff, '2026-11-08T16:30:00.000Z'); // Nov 9, 00:30 Manila
  draft = updateAttendanceGroup(draft, arrival, '2026-11-10');
  assert.equal(draft.timeInOpen, '2026-11-10T15:00:00.000Z');
  assert.equal(draft.timeInCutoff, '2026-11-10T16:30:00.000Z');
  draft = updateAttendanceGroup(draft, arrival, '');
  assert.equal(attendanceClock(draft, 'timeInOpen'), '23:00');
  assert.equal(attendanceGroupDate(draft, arrival, '2026-11-12'), '');
  draft = updateAttendanceGroup(draft, arrival, '2026-11-12');
  assert.equal(draft.timeInOpen, '2026-11-12T15:00:00.000Z');
  assert.match(render(ManagedEventCard, { event }), /View attendance times/);
  console.log('Session forms, Manila timestamps, separate completion states and legacy event rendering passed.');
} finally { await server.close(); }
