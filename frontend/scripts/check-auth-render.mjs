import assert from 'node:assert/strict';
import fs from 'node:fs';
import React from 'react';
import { renderToString } from 'react-dom/server';
import { MemoryRouter, matchRoutes } from 'react-router-dom';
import { createServer } from 'vite';
const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom' });
try {
  const { default: AuthPage } = await server.ssrLoadModule('/src/pages/auth/AuthPage.jsx');
  const { ThemeProvider } = await server.ssrLoadModule('/src/context/ThemeContext.jsx');
  const { default: SecuritySettings } = await server.ssrLoadModule('/src/components/settings/SecuritySettings.jsx');
  const render = (Component, path) => renderToString(React.createElement(MemoryRouter, { initialEntries: [path] }, React.createElement(ThemeProvider, null, React.createElement(Component))));
  const login = render(AuthPage, '/auth');
  assert.match(login, /Forgot Password\?/);
  assert.match(login, /Sign In/);
  assert.doesNotMatch(login, /security PIN|trusted device|Forgot your security/);
  const signup = render(AuthPage, '/auth/signup');
  assert.match(signup, /Create Account/);
  assert.doesNotMatch(signup, /security PIN/);
  const security = render(SecuritySettings, '/student/dashboard/security');
  assert.match(security, /Face verification/);
  assert.doesNotMatch(security, /Security PIN|Trusted devices|Rotate my PIN|PIN recovery/);
  const dashboard = fs.readFileSync('src/pages/StudentDashboard.jsx', 'utf8');
  const enrollTarget = dashboard.match(/to="([^"]+)"/)[1];
  assert.equal(matchRoutes([{path:'/student/dashboard',children:[{path:'profile',id:'enrollment'}]}],enrollTarget)?.at(-1).route.id, 'enrollment');
  // Verify signing out of onboarding also removes the student-scoped token.
  const store = new Map([['token','old'], ['token_student','old'], ['token_admin','admin']]);
  globalThis.localStorage = { getItem: (k) => store.get(k), removeItem: (k) => store.delete(k) };
  const { clearAuth } = await server.ssrLoadModule('/src/utils/auth.js');
  clearAuth('student');
  assert.equal(store.has('token_student'), false);
  assert.equal(store.get('token_admin'), 'admin');
  const sessionToken = (role, id = "student-1", expired = false) => `test.${Buffer.from(JSON.stringify({ id, role, exp: Math.floor(Date.now() / 1000) + (expired ? -60 : 3600) })).toString("base64url")}.test`;
  const studentToken = sessionToken("student");
  const organizerToken = sessionToken("organizer");
  const adminToken = sessionToken("admin", "admin-1");
  globalThis.localStorage.setItem = (key, value) => store.set(key, value);
  globalThis.window = { location: { pathname: "/student/dashboard", href: "/student/dashboard" } };
  const { getToken, getUserFromToken } = await server.ssrLoadModule('/src/utils/auth.js');
  store.clear();store.set("token", organizerToken);
  assert.equal(getToken(), null, "another portal's generic token must not enter a student request");
  assert.equal(getUserFromToken(), null);
  store.set("token", studentToken);
  assert.equal(getToken(), studentToken);
  assert.equal(store.get("token_student"), studentToken, "legacy student sessions must be pinned before another tab signs in");
  store.set("token", organizerToken);
  assert.equal(getToken(), studentToken, "another tab's organizer login must not replace student auth");
  store.set("token_student", organizerToken);
  assert.equal(getToken(), null, "wrong-role tokens under a student key must be rejected");
  store.set("token_student", sessionToken("student", "student-1", true));
  assert.equal(getToken(), null, "expired student keys cannot fall back to organizer auth");
  store.set("token_student", studentToken);store.set("token_organizer", organizerToken);store.set("token_admin", adminToken);
  const { default: api } = await server.ssrLoadModule('/src/api/axios.js');
  const authenticateRequest = api.interceptors.request.handlers[0].fulfilled;
  assert.equal(authenticateRequest({url:"/student/community-service",headers:{}}).headers.Authorization, `Bearer ${studentToken}`);
  window.location.pathname = "/organizer/dashboard";
  assert.throws(() => authenticateRequest({url:"/student/community-service",headers:{}}), /Student portal is no longer active/);
  assert.equal(authenticateRequest({url:"/admin/users",headers:{}}).headers.Authorization, `Bearer ${organizerToken}`, "organizer student directories still use the organizer grant");
  assert.equal(authenticateRequest({url:"/student/academic-status",headers:{}}).headers.Authorization, `Bearer ${organizerToken}`);
  assert.equal(authenticateRequest({url:"/student/security/face-appeals",headers:{}}).headers.Authorization, `Bearer ${organizerToken}`);
  assert.equal(authenticateRequest({url:"/account/face",headers:{}}).headers.Authorization, `Bearer ${organizerToken}`);
  assert.throws(() => authenticateRequest({url:"/student/excuses",headers:{}}), /Student portal is no longer active/);
  window.location.pathname = "/student/dashboard";store.delete("token_student");
  assert.throws(() => authenticateRequest({url:"/student/community-service",headers:{}}), /fresh sign-in/);
  assert.equal(window.location.href, "/auth");
  store.set("token_student", studentToken);store.set("token", studentToken);window.location.pathname="/student/dashboard";
  const { fetchNotificationCount } = await server.ssrLoadModule('/src/utils/notificationCount.js');
  let countRequests=0;
  const originalAdapter=api.defaults.adapter;
  api.defaults.adapter=async config=>{
    countRequests++;
    if(countRequests===1)throw {response:{status:500},config};
    return {data:{count:7},status:200,statusText:"OK",headers:{},config};
  };
  assert.equal(await fetchNotificationCount(new AbortController().signal),7);
  assert.equal(countRequests,2,"temporary unread-count failures should recover");
  countRequests=0;
  api.defaults.adapter=async config=>{countRequests++;throw {response:{status:403},config};};
  await assert.rejects(fetchNotificationCount(new AbortController().signal));
  assert.equal(countRequests,1,"permissions failures must not be retried");
  countRequests=0;
  api.defaults.adapter=async config=>{countRequests++;return {data:{count:0},status:200,statusText:"OK",headers:{},config};};
  assert.equal(await fetchNotificationCount(new AbortController().signal),0);
  const aborted=new AbortController();aborted.abort();await assert.rejects(fetchNotificationCount(aborted.signal));
  assert.equal(countRequests,1,"unmounted bells must cancel rather than retry");
  api.defaults.adapter=originalAdapter;
  delete globalThis.window;
  delete globalThis.localStorage;
  console.log('PASS: auth/face settings, legacy session migration, cross-portal token isolation, stale/expired session rejection and student ledger request authentication.');
} finally { await server.close(); }
